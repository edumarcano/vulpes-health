export function validMetricNumber(
  metric: RegistryMetric,
  value: number,
): boolean {
  if (!Number.isFinite(value)) return false;
  switch (metricRegistry[metric].representation) {
    case 'positive':
      return value > 0;
    case 'nonnegative':
      return value >= 0;
    case 'percentage':
      return value >= 0 && value <= 100;
    case 'integer':
      return Number.isSafeInteger(value) && value >= 0;
    case 'signed':
      return true;
  }
}

